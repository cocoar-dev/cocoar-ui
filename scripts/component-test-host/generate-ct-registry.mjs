import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { Project, SyntaxKind } from 'ts-morph';

import { loadCtHostConfig } from './ct-host-config.mjs';

const PROJECT_ROOT = path.resolve(process.cwd());

const config = await loadCtHostConfig(PROJECT_ROOT);

const OUTPUT_FILE = config.outputFileAbs;
const CT_STORIES_ROOT = config.ctStoriesRootAbs;

// Keep scanning narrow for performance.
// - `*.component.ts`: only within the CT stories folder.
// - `*.ct-story.ts`: within search roots (typically CT stories + libs).
const SEARCH_ROOTS = config.searchRootsAbs;

const IGNORED_DIR_NAMES = new Set(config.ignoredDirNames);

const TSCONFIG_PATH = config.tsconfigPathAbs;

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function walkForCtStoryFiles(dirPath, results) {
  if (!(await pathExists(dirPath))) return;

  const entries = await fs.readdir(dirPath, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;

    const fullPath = path.join(dirPath, entry.name);

    if (entry.isDirectory()) {
      if (IGNORED_DIR_NAMES.has(entry.name)) continue;
      await walkForCtStoryFiles(fullPath, results);
      continue;
    }

    if (!entry.isFile()) continue;

    const isCtStoryFile = entry.name.endsWith('.ct-story.ts');
    const isComponentFile =
      dirPath.startsWith(CT_STORIES_ROOT) && entry.name.endsWith('.component.ts');

    if (!isCtStoryFile && !isComponentFile) continue;

    results.push(fullPath);
  }
}

function toPosixPath(p) {
  return p.split(path.sep).join('/');
}

function importPath(fromFilePath, toFilePath) {
  const fromDir = path.dirname(fromFilePath);
  let rel = path.relative(fromDir, toFilePath);
  rel = rel.replace(/\\/g, '/');
  rel = rel.replace(/\.ts$/, '');
  if (!rel.startsWith('.')) rel = `./${rel}`;
  return rel;
}

function formatHeader() {
  return [
    '// This file is auto-generated by scripts/component-test-host/generate-ct-registry.mjs',
    '// Do not edit manually.',
    '',
  ].join('\n');
}

async function resolveRelativeTsPathAsync(fromFilePath, moduleSpecifier) {
  if (!moduleSpecifier.startsWith('.')) return null;

  const base = path.resolve(path.dirname(fromFilePath), moduleSpecifier);
  const candidates = [
    `${base}.ts`,
    `${base}.tsx`,
    path.join(base, 'index.ts'),
    path.join(base, 'index.tsx'),
  ];

  for (const candidate of candidates) {
    if (await pathExists(candidate)) return candidate;
  }
  return null;
}

function unwrapNullishUnion(type) {
  if (!type.isUnion()) return { type, hadNullish: false };

  const unionTypes = type.getUnionTypes();
  const nonNullish = unionTypes.filter((t) => !t.isNull() && !t.isUndefined());
  if (nonNullish.length === unionTypes.length) return { type, hadNullish: false };
  if (nonNullish.length === 1) return { type: nonNullish[0], hadNullish: true };

  // Still a union after unwrapping.
  return { type: type.getApparentType(), hadNullish: true };
}

function inferParserForType(type) {
  const { type: unwrapped } = unwrapNullishUnion(type);

  if (unwrapped.isBoolean()) {
    return { kind: 'boolean', expr: '(raw: string) => ctParseBoolean(raw)' };
  }

  if (unwrapped.isNumber()) {
    return { kind: 'number', expr: '(raw: string) => ctParseNumber(raw)' };
  }

  const union = unwrapped.isUnion() ? unwrapped.getUnionTypes() : null;
  if (union) {
    const stringLiterals = union
      .filter((t) => !t.isNull() && !t.isUndefined())
      .filter((t) => t.isStringLiteral());

    if (stringLiterals.length === union.filter((t) => !t.isNull() && !t.isUndefined()).length) {
      const values = stringLiterals.map((t) => t.getLiteralValue());

      // Avoid generating huge enums (e.g. icon name unions) that bloat bundles.
      if (values.length > 0 && values.length <= 50) {
        const unique = Array.from(new Set(values));
        const list = unique.map((v) => JSON.stringify(v)).join(', ');
        return { kind: 'enum', expr: `ctParseEnum([${list}])` };
      }

      return { kind: 'string', expr: '(raw: string) => ctParseString(raw)' };
    }
  }

  if (unwrapped.isString()) {
    return { kind: 'string', expr: '(raw: string) => ctParseString(raw)' };
  }

  // Default: accept raw string.
  return { kind: 'string', expr: '(raw: string) => ctParseString(raw)' };
}

function getGenericTypeArgName(typeNode) {
  if (!typeNode || typeNode.getKind() !== SyntaxKind.TypeReference) return null;
  const typeArgs = typeNode.getTypeArguments();
  if (!typeArgs || typeArgs.length === 0) return null;
  const first = typeArgs[0];
  if (first.getKind() === SyntaxKind.TypeReference) {
    return first.getText();
  }
  return first.getText();
}

function isCtStoryTypeNode(typeNode) {
  if (!typeNode || typeNode.getKind() !== SyntaxKind.TypeReference) return false;
  const typeName = typeNode.getText();
  // Covers CtStory<...> as well as qualified imports (rare).
  return (
    typeName.startsWith('CtStory<') || typeName.includes('.CtStory<') || typeName === 'CtStory'
  );
}

function findCtStoryDecls(sourceFile) {
  const results = [];
  for (const stmt of sourceFile.getVariableStatements()) {
    for (const decl of stmt.getDeclarations()) {
      const typeNode = decl.getTypeNode();
      if (!isCtStoryTypeNode(typeNode)) continue;

      const typeArgName = getGenericTypeArgName(typeNode);
      if (!typeArgName) {
        throw new Error(
          `CtStory declaration '${decl.getName()}' in ${sourceFile.getFilePath()} must declare a generic type (e.g. CtStory<MyStoryComponent>).`
        );
      }

      results.push({ decl, typeArgName });
    }
  }
  return results;
}

function readStringProperty(objectLiteral, propertyName) {
  const prop = objectLiteral.getProperty(propertyName);
  if (!prop || prop.getKind() !== SyntaxKind.PropertyAssignment) return null;
  const initializer = prop.getInitializer();
  if (!initializer) return null;
  if (initializer.getKind() === SyntaxKind.StringLiteral) {
    return initializer.getLiteralValue();
  }
  return null;
}

function hasProperty(objectLiteral, propertyName) {
  return Boolean(objectLiteral.getProperty(propertyName));
}

function resolveImportedTypeModule(sourceFile, typeName) {
  const importDecls = sourceFile.getImportDeclarations();
  for (const decl of importDecls) {
    const named = decl.getNamedImports();
    for (const spec of named) {
      const name = spec.getNameNode().getText();
      const alias = spec.getAliasNode()?.getText();
      const matches = name === typeName || alias === typeName;
      if (!matches) continue;

      return decl.getModuleSpecifierValue();
    }
  }
  return null;
}

function getInputSignalParsers(componentClass) {
  const props = componentClass.getProperties();
  const result = [];

  for (const prop of props) {
    const name = prop.getName();
    const init = prop.getInitializerIfKind(SyntaxKind.CallExpression);
    if (!init) continue;

    const callee = init.getExpression();
    const calleeText = callee.getText();
    if (calleeText !== 'input' && calleeText !== 'input.required') continue;

    const typeArg = init.getTypeArguments()[0];
    const type = typeArg ? typeArg.getType() : prop.getType();
    const parser = inferParserForType(type);
    result.push({ name, parser });
  }

  return result;
}

async function main() {
  const files = [];
  for (const root of SEARCH_ROOTS) {
    await walkForCtStoryFiles(root, files);
  }

  files.sort((a, b) => a.localeCompare(b));

  const project = new Project({
    tsConfigFilePath: TSCONFIG_PATH,
    skipAddingFilesFromTsConfig: true,
  });

  const storyModules = [];
  const storyIdOrigins = new Map();
  for (const storyFilePath of files) {
    const storyFile = project.addSourceFileAtPath(storyFilePath);
    const storyDecls = findCtStoryDecls(storyFile);

    // Ignore files with no CtStory declarations (e.g. component templates).
    if (storyDecls.length === 0) continue;

    for (const { decl, typeArgName } of storyDecls) {
      const initializer = decl.getInitializerIfKind(SyntaxKind.ObjectLiteralExpression);
      if (!initializer) {
        throw new Error(
          `CtStory declaration '${decl.getName()}' in ${storyFilePath} must be an object literal initializer.`
        );
      }

      const storyId = readStringProperty(initializer, 'id');
      if (!storyId) {
        throw new Error(
          `CtStory declaration '${decl.getName()}' in ${storyFilePath} must define a string literal id: { id: '...' }.`
        );
      }

      const origin = storyIdOrigins.get(storyId);
      if (origin) {
        const here = `${toPosixPath(path.relative(PROJECT_ROOT, storyFilePath))}:${decl.getName()}`;
        throw new Error(
          `Duplicate CtStory id '${storyId}'.\n` +
            `- First: ${origin}\n` +
            `- Next:  ${here}\n` +
            `IDs must be globally unique. Choose a new id (hierarchical ids like 'coar-input/basic' are fine).`
        );
      }
      storyIdOrigins.set(
        storyId,
        `${toPosixPath(path.relative(PROJECT_ROOT, storyFilePath))}:${decl.getName()}`
      );

      const hasOverrides =
        hasProperty(initializer, 'inputs') || hasProperty(initializer, 'providers');
      const isExported = decl.getVariableStatement()?.isExported() ?? false;

      // If story is declared inside a component module, avoid importing it into the registry
      // (would eager-load the story component chunk). Non-exported stories are also not importable.
      const canImportMeta = isExported && storyFilePath.endsWith('.ct-story.ts') && hasOverrides;

      const moduleSpec = resolveImportedTypeModule(storyFile, typeArgName);
      const localClass = storyFile.getClass(typeArgName);
      const componentTsPath = localClass
        ? storyFilePath
        : moduleSpec
        ? await resolveRelativeTsPathAsync(storyFilePath, moduleSpec)
        : null;

      if (!componentTsPath) {
        throw new Error(
          `Unable to resolve story component for CtStory generic type '${typeArgName}' in ${storyFilePath}. If the component is in another file, import it as a type.`
        );
      }

      const componentFile = project.addSourceFileAtPath(componentTsPath);
      storyModules.push({
        storyFilePath,
        storyFile,
        metaImportPath: canImportMeta ? importPath(OUTPUT_FILE, storyFilePath) : null,
        metaExportName: decl.getName(),
        metaIsImportable: canImportMeta,
        storyId,
        hasOverrides,
        isExported,
        typeArgName,
        componentFilePath: componentTsPath,
        componentImportPath: importPath(OUTPUT_FILE, componentTsPath),
        componentExportName: typeArgName,
        componentFile,
      });

      if (hasOverrides && !canImportMeta) {
        process.stderr.write(
          `CT story '${storyId}' in ${toPosixPath(
            path.relative(PROJECT_ROOT, storyFilePath)
          )}: overrides (inputs/providers) are ignored unless the story is exported and defined in a .ct-story.ts file.\n`
        );
      }
    }
  }

  project.resolveSourceFileDependencies();

  const stories = storyModules.map((mod, index) => {
    const componentClass = mod.componentFile.getClass(mod.componentExportName);
    if (!componentClass) {
      throw new Error(
        `Expected class '${mod.componentExportName}' in ${mod.componentFilePath} (referenced by ${mod.storyFilePath}).`
      );
    }

    const inputParsers = getInputSignalParsers(componentClass);
    return {
      index,
      ...mod,
      inputParsers,
    };
  });

  const usedParserKinds = new Set();
  for (const story of stories) {
    for (const { parser } of story.inputParsers) {
      usedParserKinds.add(parser.kind);
    }
  }

  const parserImports = ['ctParseString'];
  if (usedParserKinds.has('boolean')) parserImports.push('ctParseBoolean');
  if (usedParserKinds.has('number')) parserImports.push('ctParseNumber');
  if (usedParserKinds.has('enum')) parserImports.push('ctParseEnum');
  parserImports.sort();

  const metaImportsByPath = new Map();
  for (const s of stories) {
    if (!s.metaImportPath) continue;
    const name = `storyMeta${s.index}`;
    const entry = metaImportsByPath.get(s.metaImportPath) ?? [];
    entry.push(`${s.metaExportName} as ${name}`);
    metaImportsByPath.set(s.metaImportPath, entry);
  }

  const metaImports = Array.from(metaImportsByPath.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([importPathValue, named]) => `import { ${named.join(', ')} } from '${importPathValue}';`);

  const entryDecls = stories.map((s) => {
    const autoInputsLines = s.inputParsers.map(
      ({ name, parser }) => `  ${JSON.stringify(name)}: ${parser.expr},`
    );

    const providersLine = s.metaImportPath
      ? `  providers: storyMeta${s.index}.providers,`
      : `  providers: undefined,`;
    const inputsLine = s.metaImportPath
      ? `  inputs: mergeInputs(autoInputs${s.index}, storyMeta${s.index}.inputs),`
      : `  inputs: mergeInputs(autoInputs${s.index}, undefined),`;

    return [
      `const autoInputs${s.index} = {`,
      ...autoInputsLines,
      `} as const;`,
      ``,
      `const entry${s.index}: CtEntry = {`,
      `  id: ${JSON.stringify(s.storyId)},`,
      `  loadComponent: async () => {`,
      `    const mod = await import(${JSON.stringify(s.componentImportPath)});`,
      `    return mod.${s.componentExportName};`,
      `  },`,
      providersLine,
      inputsLine,
      `};`,
      ``,
    ].join('\n');
  });

  const registryEntries = stories.map((s) => `  [entry${s.index}.id]: entry${s.index},`);

  const content =
    formatHeader() +
    [
      `import type { CtEntry, CtInputOverrides, CtRegistry } from './ct-types';`,
      `import type { CtInputParser } from './ct-parsers';`,
      `import { ${parserImports.join(', ')} } from './ct-parsers';`,
      ...metaImports,
      ``,
      `function mergeInputs(`,
      `  autoInputs: Record<string, CtInputParser>,`,
      `  overrides: CtInputOverrides | undefined`,
      `): Record<string, CtInputParser> {`,
      `  if (!overrides) return autoInputs;`,
      `  const merged: Record<string, CtInputParser> = { ...autoInputs };`,
      `  for (const [key, value] of Object.entries(overrides)) {`,
      `    if (value === false) {`,
      `      delete merged[key];`,
      `      continue;`,
      `    }`,
      `    merged[key] = value;`,
      `  }`,
      `  return merged;`,
      `}`,
      ``,
      ...entryDecls,
      `const registry: CtRegistry = {`,
      ...registryEntries,
      `};`,
      ``,
      `export const CT_REGISTRY: CtRegistry = Object.freeze(registry);`,
      '',
    ].join('\n');

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, content, 'utf8');

  process.stdout.write(
    `Generated ${toPosixPath(path.relative(PROJECT_ROOT, OUTPUT_FILE))} from ${
      files.length
    } story file(s).\n`
  );
}

await main();
