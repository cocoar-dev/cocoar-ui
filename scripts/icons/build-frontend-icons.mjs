#!/usr/bin/env node

/**
 * Build Frontend Icons
 *
 * Generates core-icons.ts for the Angular icon component from /assets/icons
 *
 * Usage: node scripts/icons/build-frontend-icons.mjs
 */

import { readdir, readFile, writeFile } from 'fs/promises';
import { join, parse, dirname } from 'path';
import { fileURLToPath } from 'url';
import { findGitRoot } from '../shared/git-utils.mjs';
import { normalizeSvg, validateSvg, escapeSvgForJs } from '../shared/svg-utils.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const GIT_ROOT = await findGitRoot(__dirname);
const SOURCE_DIR = join(GIT_ROOT, 'assets', 'icons');
const OUTPUT_FILE = join(
  GIT_ROOT,
  'libs',
  'ui',
  'components',
  'src',
  'lib',
  'display',
  'icon',
  'core-icons.ts'
);

/**
 * Build icons from /assets/icons to core-icons.ts
 */
async function buildIcons() {
  console.warn('🔨 Building frontend icons...');
  console.warn(`📂 Source: ${SOURCE_DIR}`);
  console.warn(`📝 Output: ${OUTPUT_FILE}`);

  try {
    // Read all SVG files
    const files = await readdir(SOURCE_DIR);
    const svgFiles = files.filter((f) => f.endsWith('.svg')).sort();

    if (svgFiles.length === 0) {
      console.warn('⚠️  No SVG files found in /assets/icons/');
      return;
    }

    console.warn(`📁 Found ${svgFiles.length} SVG files`);

    // Process each SVG and inline content
    const iconEntries = [];

    for (const file of svgFiles) {
      const { name } = parse(file);
      const filePath = join(SOURCE_DIR, file);
      const content = await readFile(filePath, 'utf-8');

      // Validate and normalize
      validateSvg(content, file);
      const normalized = normalizeSvg(content);
      const escaped = escapeSvgForJs(normalized);

      iconEntries.push(`  '${name}': \`${escaped}\`,`);

      console.warn(`  ✓ ${name}`);
    }

    // Generate TypeScript file with inlined SVG strings
    const output = `/**
   * Built-in icon registry.
   *
   * ⚠️  DO NOT EDIT THIS FILE MANUALLY
   *
   * This file is auto-generated from /assets/icons/*.svg files.
   * To add new icons:
   * 1. Add SVG files to /assets/icons/
   * 2. Run: pnpm build:icons
   * 3. Commit the generated file
   *
   * Icons are inlined as strings for maximum portability.
   */

export const CORE_ICONS = {
${iconEntries.join('\n')}
};

export type CoreIconName = keyof typeof CORE_ICONS | (string & {});
`;

    await writeFile(OUTPUT_FILE, output, 'utf-8');

    console.warn(`✅ Generated core-icons.ts with ${svgFiles.length} icons`);
    console.warn(`📝 Icon names: ${svgFiles.map((f) => parse(f).name).join(', ')}`);
  } catch (error) {
    console.error('❌ Error building icons:', error);
    process.exit(1);
  }
}

buildIcons();
